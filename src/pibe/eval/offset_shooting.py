r"""Score a candidate sensor offset by simulation, starting from the bank's estimates.

The amortized EPIBE bank (``ebm.location: amortized``) produces a full estimate
for *any* assumed offset :math:`\mu`: feed it :math:`y - \mu` and it returns
:math:`\hat x(0)`, :math:`\hat\theta` and :math:`\hat a`.  This module decides
between offsets.

Why simulation and not the bank's own loss
------------------------------------------
The bank's physics residuals are enforced softly: each cell's new coordinate can
satisfy its own equation exactly, so the last residual reaches the objective
only through a consistency penalty filtered by the stable dynamics of that
equation.  A wrong offset can therefore be hidden at a cost comparable to the
networks' own approximation error, and profiling the bank objective over
:math:`\mu` mixes the physics with how well the network happens to fit near each
offset.  A simulated trajectory has none of that freedom: it is generated by
the model from :math:`(x_0, \theta, a)`, so

.. math::

    J(\mu) = \min_{x_0, \theta, a}\ \frac{1}{PN}\sum_{\ell, i}
             \bigl(y^\ell(t_i) - \mu - x_1(t_i; x_0^\ell, \theta, a^\ell)\bigr)^2

is the exact physics profile on the measured data, which bottoms out at the
noise variance at the true offset.  The bank's estimates start the inner
minimization close to its solution, so a few hundred steps suffice.

The inner problem shares :math:`\theta` across trajectories (one physical
system) and gives each trajectory its own :math:`x_0` and :math:`a`.
"""

from __future__ import annotations

import torch
from torch import Tensor

from pibe.basis.base import DisturbanceBasis
from pibe.systems.base import TriangularSystem


def simulate_output(system: TriangularSystem, basis: DisturbanceBasis, x0: Tensor,
                    theta: Tensor, a: Tensor, t_data: Tensor, substeps: int = 2) -> Tensor:
    r"""Batched RK4 of the triangular system; returns :math:`x_1` on ``t_data``.

    ``x0`` is ``(P, n)``, ``theta`` is ``(n-1,)`` shared or ``(P, n-1)``, ``a``
    is ``(P, q)``.  Differentiable in all three.
    """
    n = system.n
    P = x0.shape[0]
    th = theta.reshape(1, -1).expand(P, -1) if theta.ndim == 1 else theta
    dt = float(t_data[1] - t_data[0]) / substeps
    steps = (len(t_data) - 1) * substeps
    half = torch.arange(0, 2 * steps + 1, dtype=t_data.dtype, device=t_data.device) * (dt / 2)
    forcing = a @ basis.evaluate(half).T  # (P, 2 * steps + 1)

    def rhs(x: Tensor, j: int) -> Tensor:
        parts = [x[:, i + 1] + system.f(i + 1, x[:, : i + 1], th[:, : i + 1]) for i in range(n - 1)]
        parts.append(system.f_last(x, th) + forcing[:, j])
        return torch.stack(parts, dim=-1)

    x = x0
    out = [x[:, 0]]
    for i in range(steps):
        k1 = rhs(x, 2 * i)
        k2 = rhs(x + 0.5 * dt * k1, 2 * i + 1)
        k3 = rhs(x + 0.5 * dt * k2, 2 * i + 1)
        k4 = rhs(x + dt * k3, 2 * i + 2)
        x = x + dt / 6.0 * (k1 + 2 * k2 + 2 * k3 + k4)
        if (i + 1) % substeps == 0:
            out.append(x[:, 0])
    return torch.stack(out, dim=1)


def shooting_cost(bank, y: Tensor, t_data: Tensor, t_coll: Tensor, offset: float,
                  steps: int = 150, lr: float = 0.02, substeps: int = 2) -> tuple[float, Tensor]:
    """:math:`J(\\mu)` for one offset, and the refined shared parameters."""
    system, basis = bank.system, bank.basis
    with torch.no_grad():
        est = bank.estimate(y, t_data, t_coll, offset=offset)
    x0 = est.x[:, 0, :].clone().requires_grad_(True)
    theta = est.theta.mean(0).clone().requires_grad_(True)
    a = est.a.clone().requires_grad_(True)
    lo, hi = system.theta_bounds[:, 0], system.theta_bounds[:, 1]
    optimizer = torch.optim.Adam([x0, theta, a], lr=lr)
    schedule = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=max(1, steps))
    target = y - offset
    with torch.enable_grad():
        for _ in range(steps):
            optimizer.zero_grad(set_to_none=True)
            loss = ((target - simulate_output(system, basis, x0, theta, a, t_data, substeps)) ** 2).mean()
            loss.backward()
            optimizer.step()
            schedule.step()
            with torch.no_grad():
                theta.copy_(torch.maximum(torch.minimum(theta, hi), lo))
    with torch.no_grad():
        final = float(((target - simulate_output(system, basis, x0, theta, a, t_data, substeps)) ** 2).mean())
    return final, theta.detach()


def select_offset(bank, y: Tensor, t_data: Tensor, t_coll: Tensor, window: tuple[float, float],
                  grid: int, coarse_steps: int, fine_points: int, fine_steps: int,
                  log=None, centre: float | None = None, cache: dict | None = None,
                  on_score=None) -> tuple[float, list[tuple[float, float]], list[tuple[float, float]]]:
    r"""Two-pass search for the offset minimizing :math:`J(\mu)`.

    A coarse grid with a short refinement finds the basin; ``fine_points``
    offsets spanning one coarse step either side of its minimizer (or of
    ``centre``, which skips the coarse pass) are then
    rescored with a long refinement, and the offset is the vertex of a
    least-squares quadratic through them.

    Both passes are needed.  With a short refinement the inner fit has not
    converged, so each score still carries how good the bank's starting point
    was at that offset; that bias moves the minimizer by several hundredths.
    A converged fit removes it but costs four times as much, so it is spent
    only where the answer is.  A three-point parabola is not enough either:
    the profile is asymmetric about its minimum and the vertex is dragged
    towards the flatter side.
    """
    say = log or (lambda *args: None)
    cache = {} if cache is None else cache

    def score(c: float, steps: int, label: str) -> float:
        # Keyed by pass and offset, so a resumed job skips what it has scored.
        key = f"{label}:{c:.6f}"
        if key in cache:
            say("  %s offset %+.4f | misfit %.6e | (cached)", label, c, cache[key])
            return cache[key]
        cost, theta = shooting_cost(bank, y, t_data, t_coll, c, steps=steps)
        cache[key] = cost
        say("  %s offset %+.4f | misfit %.6e | theta %s", label, c, cost,
            [round(v, 4) for v in theta.tolist()])
        if on_score is not None:
            on_score(cache)
        return cost

    coarse = []
    if centre is None:
        offsets = torch.linspace(window[0], window[1], grid, dtype=y.dtype).tolist()
        for c in offsets:
            coarse.append((c, score(c, coarse_steps, "coarse")))
        centre = min(coarse, key=lambda r: r[1])[0]
    if fine_points < 3:
        return centre, coarse, []
    step = (window[1] - window[0]) / (grid - 1)
    lo, hi = max(window[0], centre - step), min(window[1], centre + step)
    fine = []
    for c in torch.linspace(lo, hi, fine_points, dtype=y.dtype).tolist():
        fine.append((c, score(c, fine_steps, "fine  ")))
    x = torch.tensor([r[0] for r in fine], dtype=torch.float64)
    j = torch.tensor([r[1] for r in fine], dtype=torch.float64)
    design = torch.stack([x ** 2, x, torch.ones_like(x)], dim=1)
    a, b, _ = torch.linalg.lstsq(design, j.unsqueeze(1)).solution.squeeze(1).tolist()
    best = min(fine, key=lambda r: r[1])[0]
    if a > 0:
        best = min(max(-b / (2 * a), lo), hi)
    return float(best), coarse, fine
